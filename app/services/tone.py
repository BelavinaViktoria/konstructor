def tone(q: dict, answer: str | None) -> dict:
    """Возвращает {'t': 'neg'|'warn'|'ok'|'none', 'why': ...}."""
    ty = q.get("ty")
    if not answer or ty in SILENT_TYPES:
        return {"t": "none"}
    if ty == "know":
        if answer == "Не знает":
            return {"t": "neg", "why": "сотрудник не знает ответа"}
        if answer == "Знает частично":
            return {"t": "warn", "why": "сотрудник знает ответ частично"}
        return {"t": "ok"}
    if ty == "many":
        parts = [x.strip() for x in answer.split(";")]
        if any(RX_NEG.search(x) for x in parts):
            return {"t": "neg", "why": "выбран негативный вариант"}
        if re.search("помогает", q["t"], re.I) and not any(re.search("Наставник|руководитель", x, re.I) for x in parts):
            return {"t": "warn", "why": "сотрудник не называет среди помощников ни наставника, ни руководителя"}
        if any(RX_WARN.search(x) for x in parts):
            return {"t": "warn", "why": "есть настораживающий вариант"}
        return {"t": "ok"}
    if RX_OK.search(answer):
        return {"t": "ok"}
    if ty == "long" and RX_NO_PROBLEM.search(answer.strip()):
        return {"t": "ok"}
    if ty == "one" and RX_PARTIAL.search(answer):
        return {"t": "warn", "why": "ответ частичный: проблема решена не полностью"}

    def clause(fragment: str) -> str:
        part = next((x for x in re.split(r"[,.;!?]", answer) if fragment.lower() in x.lower()), fragment)
        return part.strip()

    match = (RX_NEG_LONG if ty == "long" else RX_NEG).search(answer)
    if match:
        why = f"в ответе есть прямое указание на проблему: «{clause(match.group(0))}»" if ty == "long" else "ответ прямо указывает на проблему"
        return {"t": "neg", "why": why}
    match = RX_WARN.search(answer)
    if match:
        why = f"в ответе есть оговорка: «{clause(match.group(0))}»" if ty == "long" else "ответ частичный: проблема решена не полностью"
        return {"t": "warn", "why": why}
    return {"t": "ok"}


def question_key(q: dict) -> str:
    if q.get("ty") == "know":
        return "know"
    return next((key for pattern, key in PQ if re.search(pattern, q["t"], re.I)), "other")


def snippet(answer: str) -> str:
    return "«" + (answer[:72].strip() + "…" if len(answer) > 72 else answer) + "»"


def signal_title(key: str, q: dict, answer: str, t: str) -> str:
    if key in ("trouble", "comment"):
        if re.search("наставник", answer, re.I):
            return "Наставник недоступен: сотруднику некому задавать вопросы"
        return ("Трудность: " if key == "trouble" else "Комментарий: ") + snippet(answer)
    if key == "know":
        return "Пробел в знаниях о компании: " + q["t"][:80]
    pair = PT.get(key)
    return (pair[0] if t == "neg" else pair[1]) if pair else q["t"]


def build_survey_signals(survey: dict, answers: dict) -> list[dict]:
    """Каждый негативный или настораживающий ответ становится отдельным описанием сигнала."""
    out = []
    for q in survey["q"]:
        if q.get("ty") in SILENT_TYPES:
            continue
        answer = answers.get(q["t"])
        result = tone(q, answer)
        if result["t"] not in ("neg", "warn"):
            continue
        key = question_key(q)
        mentor_issue = key in ("trouble", "comment") and re.search("наставник", answer, re.I)
        info_key = "mentor" if mentor_issue else key
        out.append({
            "level": "высокий" if result["t"] == "neg" else "средний",
            "title": signal_title(key, q, answer, result["t"]),
            "detail": f"Почему это проблема: {result['why']}. {PI.get(info_key, PI['other'])}",
            "evidence": [[q["t"], answer, result["t"]]],
            "recommendation": PR.get(info_key, PR["other"]),
        })
    return out
